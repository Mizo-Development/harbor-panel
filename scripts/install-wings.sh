#!/usr/bin/env bash
set -euo pipefail
version=v1.13.4
config=''
dry_run=false
while (($#)); do
  case "$1" in
    --config) config="${2:?Configuration file required}"; shift 2 ;;
    --dry-run) dry_run=true; shift ;;
    --help) printf '%s\n' 'Usage: sudo bash scripts/install-wings.sh [--config /path/config.json] [--dry-run]'; exit 0 ;;
    *) printf 'Unknown option: %s\n' "$1" >&2; exit 1 ;;
  esac
done
if "$dry_run"; then printf 'Would install official Wings %s, Docker prerequisite required; configure from the panel.\n' "$version"; exit 0; fi
[[ $EUID -eq 0 ]] || { printf '%s\n' 'Run as root.' >&2; exit 1; }
if [[ -e /usr/local/bin/wings || -e /etc/pterodactyl/config.yml || -e /etc/systemd/system/wings.service ]]; then
  if [[ ! -f /etc/systemd/system/wings.service ]] || ! grep -q '^Description=Pterodactyl Wings for Harbor$' /etc/systemd/system/wings.service; then
    printf '%s\n' 'Existing Wings detected. Use the isolated node installer generated by Harbor instead; existing files were not changed.' >&2
    exit 1
  fi
fi
command -v docker >/dev/null || { printf '%s\n' 'Install Docker first, or use install.sh on the panel machine.' >&2; exit 1; }
case "$(uname -m)" in
  x86_64) architecture=amd64; checksum=7e763389bb5d386a7d32ccdd46cffcf1ab9ed697e5c2aca7fe44183b527cd4c0 ;;
  aarch64) architecture=arm64; checksum=516cc0b86fec092feb9893bacab2e1bf478b5477a5459ad9d722676c7549faa5 ;;
  *) printf '%s\n' 'Unsupported architecture.' >&2; exit 1 ;;
esac
artifact=$(mktemp)
trap 'test ! -f "$artifact" || unlink "$artifact"' EXIT
curl --fail --location --proto '=https' "https://github.com/pterodactyl/wings/releases/download/${version}/wings_linux_${architecture}" -o "$artifact"
printf '%s  %s\n' "$checksum" "$artifact" | sha256sum --check
install -m 0755 "$artifact" /usr/local/bin/wings
install -d -m 0700 /etc/pterodactyl
if [[ -n "$config" ]]; then install -m 0600 "$config" /etc/pterodactyl/config.yml; fi
cat > /etc/systemd/system/wings.service <<'UNIT'
[Unit]
Description=Pterodactyl Wings for Harbor
After=docker.service network-online.target
Requires=docker.service
ConditionPathExists=/etc/pterodactyl/config.yml
[Service]
User=root
WorkingDirectory=/etc/pterodactyl
ExecStart=/usr/local/bin/wings
Restart=on-failure
RestartSec=5
LimitNOFILE=4096
[Install]
WantedBy=multi-user.target
UNIT
systemctl daemon-reload
systemctl enable wings
if [[ -f /etc/pterodactyl/config.yml ]]; then systemctl restart wings; else printf '%s\n' 'Wings installed. Save the panel-generated configuration, then run: systemctl start wings'; fi
